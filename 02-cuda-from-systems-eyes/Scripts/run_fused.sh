#!/usr/bin/env bash
# =============================================================================
# run_fused.sh —— RMSNorm / online softmax 两条融合阶梯的完整测试
#
#   八个 kernel：n1 n2 n3 n4（RMSNorm）+ s1 s2 s3 s4（softmax）
#
#   和 SGEMM 那套的区别：这两个算子是【访存密集】的，
#   所以看的不是"占峰值算力"，是 MBU = 实测 GB/s ÷ 1008。
#
#   阶段：
#     0 编译 + spill 检查   ← 这一步比 SGEMM 那边更要命，见下面
#     1 正确性（含边界）
#     2 主阶梯（固定形状，看 1.5× 和 2.0× 兑现了多少）
#     3 形状扫描（decode b1 / b32 / prefill / 大批）
#     4 长行：寄存器放不下会怎样
#     5 竞态检查
#
#   ⚠ 第 0 步的 spill 检查是这份测试的命门：
#     n3/n4/s3/s4 的全部立论就是"整行留在寄存器里，只读一次 global"。
#     一旦 ptxas 报 spill stores，那行数据其实被挪到了 local memory（也就是显存），
#     于是它们退化成"读两次"，1.5× 和 2.0× 都不会出现，而且你从耗时上看不出原因。
#
#   用法：bash run_fused.sh
#         ROUNDS=1 bash run_fused.sh      # 快速过一遍
# =============================================================================
#
# ---- 给不熟悉 shell 的读者：这份脚本用到的语法，一次讲清 --------------------
#
#   #!/usr/bin/env bash  第一行的 #! 叫 shebang，告诉系统拿哪个解释器跑这个文件。
#                      写 env bash 而不是写死 /bin/bash，是为了用 PATH 里找到的那个。
#   #                  行内从 # 到行尾都是注释（shebang 那一行除外）。
#   $VAR / ${VAR}      取变量的值。${} 是为了和紧跟的字符分开，
#                      比如 "fused_${STAMP}.txt" —— 不加花括号会被当成变量名 STAMP.txt。
#   "$VAR"             几乎永远要加双引号 —— 不加的话，值里有空格就会被拆成多个参数。
#                      下面只有一处故意不加（set -- $shp），那里就是要它拆开。
#   ${VAR:-默认值}      VAR 没设置或为空时取「默认值」。ROUNDS=${ROUNDS:-3} 的意思是：
#                      允许调用者用 ROUNDS=1 bash run_fused.sh 从环境覆盖它。
#   $(命令)             命令替换：先跑命令，把它打印的内容替换到这里。
#   名字() { ...; }     定义函数。调用时直接写名字，第 1、2 个参数是 $1 $2 …
#                      函数体写在一行时，最后一条命令后面也要有分号，} 前要有空格。
#   "$@"  与  "$*"     都表示"全部参数"，但用途相反：
#                      "$@" 保持每个参数各自独立 → 拿来【执行】；
#                      "$*" 拼成一整串           → 拿来【打印】。下面 run() 里两个都用到了。
#   cmd1 | cmd2        管道：把 cmd1 的输出喂给 cmd2 的输入。
#   >  文件            把输出写进文件（覆盖）；  >>  是追加。
#   2>/dev/null        把「错误输出」丢掉（1 是正常输出，2 是错误输出）。
#   2>&1               把错误输出并进正常输出，这样管道和重定向才收得到它。
#   \$                 反斜杠转义，输出一个字面的 $ 符号，而不是去取变量。
#   for x in 一串词     按空格逐个取出。词可以来自字面量、变量展开或 $( )。
#   do … done          for / while 的循环体；if 用 then … fi 收尾。
#   A || { B; }        A 失败（返回非 0）时才执行 B。A && B 则相反。
#                      { } 把多条命令打包成一组（注意最后一条也要有分号）。
#   set -u             用到没定义过的变量就立刻报错退出，防手滑打错变量名。
#   set -- 词 词       重设位置参数：执行后 $1 $2 就变成这些词。
#                      下面拿它把 "prefill 2048" 这种「名字+数值」的配对拆成两个变量。
#   command -v xxx     查「系统里有没有 xxx 这个命令」，输出丢掉只看成败。
#   exit 1             中止脚本并返回非 0（约定：0 成功，非 0 失败）。
#
#   ---- 被测程序的调用约定 ----
#   ./fused_ops <kind> <M> <N> <iters>
#       kind   n1|n2|n3|n4|s1|s2|s3|s4
#       M      行数（= batch × seq，每行一个 block）
#       N      列数（RMSNorm 用 hidden=3584，softmax 用 seq=2048）
#       iters  计时重复次数，程序取中位数
#
# =============================================================================
set -u

# ---- 可调参数：都用 ${VAR:-默认} 写，于是能从命令行环境覆盖 ----
ROUNDS=${ROUNDS:-3}
HID=${HID:-3584}                          # Qwen2.5-7B 的 hidden_size
SEQ=${SEQ:-2048}                          # 打分行长度（上下文长度）
# date +格式 生成时间戳，$( ) 把它取出来拼进文件名 → 每次运行各自一份输出
STAMP=$(date +%Y%m%d_%H%M%S)
OUT="fused_${STAMP}.txt"                  # ${STAMP} 的花括号是为了和后面的 .txt 分开

# ---- 三个小函数 ----
# log：  "$@" = 调用时传进来的全部参数（保留原有的分词）；
#        tee 同时写屏幕和文件，-a 表示追加（没有 -a 会每次清空）
# rule： 固定打一条横线，纯粹为了日志好读
# run：  先把命令行原样记进日志（方便复现），再真正执行它。函数体是两条命令，用 ; 隔开：
#          echo "\$ $*" >>"$OUT"     ← 记日志的是这半句。\$ 输出字面的 $ 符号（模仿终端提示符），
#                                      $* 把全部参数拼成一行；>> 只写文件、不上屏幕
#          "$@" 2>&1 | tee -a "$OUT" ← 这半句才是真执行。"$@" 保持每个参数独立
#                                      （$* 会拼成一整串，不能拿来执行）；2>&1 让报错也进日志
log()  { echo "$@" | tee -a "$OUT"; }
rule() { log "-------------------------------------------------------------"; }
run()  { echo "\$ $*" >>"$OUT"; "$@" 2>&1 | tee -a "$OUT"; }

# ---------------------------------------------------------------- 环境快照
# date -Is 打 ISO 格式时间；hostname 机器名；uname -sr 内核名和版本
log "============================================================="
log " 融合算子基准 · RMSNorm + online softmax   $(date -Is)"
log " 主机 $(hostname)   $(uname -sr)"
log " hidden=$HID  seq=$SEQ  （Qwen2.5-7B 的真实维度）"
log "============================================================="
# 记下卡型号和功耗墙 —— 换机器重跑时，这几行决定数字能不能对比
run nvidia-smi --query-gpu=name,driver_version,clocks.max.sm,clocks.max.mem,power.limit --format=csv

# ---------------------------------------------------------------- 0 编译
rule
log "编译 + spill 检查"
rule
# -Xptxas -v 让 ptxas 把每个 kernel 的寄存器数 / 栈帧 / spill 打出来 —— 这一步的全部目的
# ||  前面失败才执行后面的 { }；{ } 是把多条命令打包成一组（注意最后一条也要有分号）
run nvcc -O3 -arch=sm_89 -lineinfo -Xptxas -v fused_ops.cu -o fused_ops || {
  log "!! 编译失败，停在这里"; exit 1; }
log ""
# log "" 打一个空行；下面这几行 >>> 是写给读日志的人看的验收提示，不参与计算
log ">>> 十一个 kernel 全都要是 0 bytes stack frame / 0 bytes spill stores。"
log ">>> 尤其盯住 rms_n3 / rms_n4 / sm_s3 / sm_s4 —— 它们每线程要拿 32 个寄存器"
log ">>> 存整行数据。一旦 spill，那行数据就跑到显存里去了，"
log ">>> '只读一次' 的前提作废，1.5× / 2.0× 一个都不会出现。"
log ">>> 顺带记下寄存器数：n1/n2 应该很少（十几个），n3/n4/s3/s4 应该明显更多。"

# ---------------------------------------------------------------- 1 正确性
rule
log "正确性：八个 kernel 各跑一次小规模"
rule
# for k in n1 n2 n3 n4 —— 直接给字面量列表，$k 依次取到每一个
# M 只取 64：这一步看的是校验行，不是速度，跑快点好
for k in n1 n2 n3 n4; do
  log ""; log "--- $k · M=64 N=$HID ---"
  run ./fused_ops "$k" 64 "$HID" 3
done
# softmax 这四个换成 N=$SEQ —— 行长不同，两条阶梯不能混在同一个 N 上比
for k in s1 s2 s3 s4; do
  log ""; log "--- $k · M=64 N=$SEQ ---"
  run ./fused_ops "$k" 64 "$SEQ" 3
done
log ""
log ">>> 八行都要看到 ✓ 抽样校验通过。"
log ">>> softmax 那四个尤其要看 —— online 递推写错的典型症状不是崩溃，"
log ">>> 是结果偏一点点，只有对照 CPU 才看得出来。"

log ""
log "--- 边界：N 不是 BLOCK 的整数倍（最后一轮只有部分线程有活）---"
# 1000 不是 256 的整数倍：1000 = 3×256 + 232，最后一轮有 24 个线程闲着
# 只测 n3/s3 —— 寄存器驻留那两级才有"幺元 + 越界判断"的组合风险
for k in n3 s3; do
  log ""; log "--- $k · N=1000 ---"
  run ./fused_ops "$k" 64 1000 3
done
log ">>> 这两个必须也通过。写越界判断时最容易在这里翻车。"

# ---------------------------------------------------------------- 2 主阶梯
log ""
log "============================================================="
log " 主阶梯：${ROUNDS} 轮"
log " RMSNorm  M=8192 行 × N=$HID    理论 n1→n3 = 12N/8N = 1.50×"
log " softmax  M=8192 行 × N=$SEQ    理论 s1→s3 = 16N/8N = 2.00×"
log "============================================================="
# seq 1 3 打印 1 2 3，$( ) 接住当成 for 的列表 —— 跑 ROUNDS 轮取中位数，防偶发抖动
for r in $(seq 1 "$ROUNDS"); do
  log ""
  log "##################### 第 $r 轮 #####################"
  # M=8192 是主基准形状；iters 给到 11，程序取中位数
  for k in n1 n2 n3 n4; do
    log ""; log "--- round $r · rmsnorm · $k ---"
    run ./fused_ops "$k" 8192 "$HID" 11
  done
  for k in s1 s2 s3 s4; do
    log ""; log "--- round $r · softmax · $k ---"
    run ./fused_ops "$k" 8192 "$SEQ" 11
  done
done

# ---------------------------------------------------------------- 3 形状扫描
log ""
log "============================================================="
log " 形状扫描 —— 行数变了，结论会不会变"
log "   decode b1   M=1      一个 block，128 个 SM 里 127 个在看戏"
log "   decode b32  M=32     还是填不满"
log "   prefill     M=2048   一次前向 2048 个 token"
log "   大批        M=16384  把卡喂饱，MBU 的上限在这里"
log "============================================================="
# 这里要同时带「名字」和「M 值」两个信息。shell 没有字典，常见做法是把一对
# 塞进一个字符串，循环里再拆开：
#   set -- $shp   把 $shp 按空格拆成词，重设位置参数 → $1 是名字，$2 是 M
#   注意 $shp 这里【故意不加引号】—— 加了就成一个词，拆不开了。
#   这是本脚本唯一一处不加引号的变量展开。
for shp in "decode-b1 1" "decode-b32 32" "prefill 2048" "大批 16384"; do
  set -- $shp
  nm=$1; m=$2
  log ""
  log "========== $nm : M=$m =========="
  # 每种形状只跑 n1/n3/n4 和 s1/s3/s4 —— n2/s2 是中间台阶，形状扫描里不需要
  for k in n1 n3 n4; do
    log ""; log "--- $nm · $k ---"
    run ./fused_ops "$k" "$m" "$HID" 11
  done
  for k in s1 s3 s4; do
    log ""; log "--- $nm · $k ---"
    run ./fused_ops "$k" "$m" "$SEQ" 11
  done
done

# ---------------------------------------------------------------- 4 长行
log ""
log "============================================================="
log " 长行：寄存器放不下的时候"
log "   Qwen2.5-7B 的 vocab 是 152064 —— 采样时要对这么长的一行做 softmax。"
log "   而 s3/s4 的单行上限是 BLOCK × MAXS = 256 × 32 = 8192。"
log "   下面三条命令里，前两条能跑，第三条会被程序拒绝并说明原因。"
log ""
log "   这不是实现偷懒，而是【FlashAttention 为什么必须分块】的同一个约束："
log "   行放不进片上存储 → 必须分块 → 分块就要能增量合并 softmax"
log "   → 于是 online 递推从'优化技巧'变成'必需品'。"
log "============================================================="
# 这三条不进循环，因为每条要配一句不同的说明 —— 日志是给人读的
log ""; log "--- logits softmax · s1（三趟，不吃寄存器）---"
run ./fused_ops s1 32 152064 11
log ""; log "--- logits softmax · s2（online 两趟，也不吃寄存器）---"
run ./fused_ops s2 32 152064 11
log ""; log "--- logits softmax · s3（寄存器驻留，预期被拒绝）---"
run ./fused_ops s3 32 152064 11
log ""
# 注意：这一条【预期失败】。脚本没开 set -e，加上 run() 用了管道（退出码取自末尾的 tee），
# 所以这次非 0 退出不会打断后面的步骤 —— 失败与否要靠读日志里的 ✗ 判断
log ">>> s3 应该打印 '✗ 这一级把整行存在寄存器里' 并退出（返回码 3），这是预期行为。"
log ">>> 同时注意 s1 和 s2 在这个形状上的 MBU —— 行长 152064、只有 32 行，"
log ">>> 两个数字放在一起看，能说明'长行 + 少行'是最难喂饱卡的一种形状。"

# ---------------------------------------------------------------- 5 竞态
# command -v 查这台机器上装没装 compute-sanitizer；没装就整段跳过，不报错
# >/dev/null 2>&1 把它的正常输出和错误输出都丢掉 —— 只要成败，不要内容
if command -v compute-sanitizer >/dev/null 2>&1; then
  log ""
  log "============================================================="
  log " 竞态检查 —— 放在计时之后"
  log " 这两个算子的 shared 用法比第 10 章复杂：blockReduceMaxSum 里"
  log " 同一块 shared 先写 warp 部分和、再被 0 号 warp 读、再广播，"
  log " 三个阶段之间少一个 __syncthreads 就是竞态。"
  log "============================================================="
  # 规模必须小（M=8 N=1000 跑 1 次）：racecheck 会逐条指令检查 shared 访问，
  # 慢几百倍，拿主基准的形状去跑等于死机
  for k in n3 s3 s4; do
    log ""; log "--- racecheck · $k ---"
    run compute-sanitizer --tool racecheck ./fused_ops "$k" 8 1000 1
  done
  log ""
  log ">>> 每段结尾都要看到 RACECHECK SUMMARY: 0 hazards displayed"
fi

# ---------------------------------------------------------------- 收尾
log ""
log "============================================================="
log " 完成 → $OUT"
log ""
log " 本地取回后："
log "   python parse_fused.py $OUT      # 解析成 CSV"
log "============================================================="
